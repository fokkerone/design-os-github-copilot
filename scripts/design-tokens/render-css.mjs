/**
 * Render tokens.css for Tailwind CSS v4 from the DesignOS token model.
 *
 * Structure (shadcn-compatible):
 *   :root          light values of mode-dependent tokens (semantic colors, shadows)
 *   .dark          dark overrides
 *   @theme inline  maps Tailwind namespaces to the runtime variables
 *   @theme         static tokens (palettes, typography, spacing, radius, breakpoints)
 *
 * Strict import: every Tailwind namespace the import provides is reset first
 * (`--color-*: initial`), so only imported tokens exist as utilities.
 */

/** Escape characters that are not valid in a CSS custom property name. */
export const cssIdent = (name) => name.replace(/([.])/g, '\\$1')

const decl = (name, value) => `  ${cssIdent(name)}: ${value};`

export function renderCss(model) {
  const { meta } = model
  const lines = []
  const push = (...l) => lines.push(...l)
  const block = (selector, body) => {
    if (!body.length) return
    push(`${selector} {`, ...body, '}', '')
  }
  const comment = (text) => `  /* ${text} */`

  const tokensInput = meta.inputs.find((i) => i.file === 'tokens.json')
  push(
    '/**',
    ` * ${meta.title ?? 'Design system'} — design tokens for Tailwind CSS v4`,
    ' *',
    ' * GENERATED by `npm run tokens:build` from product/design-system/import/ — do not edit.',
    ` * Source: tokens.json sha256 ${tokensInput ? tokensInput.sha256.slice(0, 16) : 'n/a'}`,
    ' * Colors are OKLCH. Dimensions are rem (16px = 1rem).',
    ' */',
    '',
    '@custom-variant dark (&:where(.dark, .dark *));',
    '',
  )

  // --- Runtime (mode-dependent) variables -------------------------------------
  const modalColors = [...model.color.semantic, ...model.color.custom.filter((c) => c.runtimeVar)]
  const modalShadows = model.shadows.filter((s) => s.runtimeVar)

  const rootBody = []
  const darkBody = []
  if (modalColors.length) {
    rootBody.push(comment('Semantic colors'))
    darkBody.push(comment('Semantic colors'))
    for (const c of modalColors) {
      if (c.light) rootBody.push(decl(c.runtimeVar, c.light.oklch))
      if (c.dark) darkBody.push(decl(c.runtimeVar, c.dark.oklch))
    }
  }
  if (modalShadows.length) {
    rootBody.push(comment('Shadows'))
    darkBody.push(comment('Shadows'))
    for (const s of modalShadows) {
      if (s.light) rootBody.push(decl(s.runtimeVar, s.light.css))
      if (s.dark) darkBody.push(decl(s.runtimeVar, s.dark.css))
    }
  }
  block(':root', rootBody)
  block('.dark', darkBody)

  const inlineBody = []
  for (const c of modalColors) inlineBody.push(decl(c.cssVar, `var(${c.runtimeVar})`))
  for (const s of modalShadows) inlineBody.push(decl(s.cssVar, `var(${s.runtimeVar})`))
  block('@theme inline', inlineBody)

  // --- Static theme ---------------------------------------------------------------
  const theme = []
  const resets = []
  const section = (title, namespaces, entries) => {
    if (!entries.length) return
    for (const ns of namespaces) if (!resets.includes(ns)) resets.push(ns)
    theme.push(comment(title))
    theme.push(...entries)
  }

  const hasColors = model.color.palettes.length || model.color.semantic.length || model.color.custom.length || model.color.alpha.length
  if (hasColors) resets.push('--color-*')
  section(
    'Colors: palettes',
    [],
    model.color.palettes.flatMap((p) => p.steps.map((s) => decl(s.cssVar, s.value.oklch))),
  )
  section(
    'Colors: alpha',
    [],
    model.color.alpha.flatMap((g) => g.steps.map((s) => decl(s.cssVar, s.value.oklch))),
  )
  section(
    'Colors: custom',
    [],
    model.color.custom.filter((c) => !c.runtimeVar && c.light).map((c) => decl(c.cssVar, c.light.oklch)),
  )

  const { fontFamilies, fontSizes, fontWeights } = model.typography
  section('Font families', fontFamilies.length ? ['--font-*'] : [], fontFamilies.map((f) => decl(f.cssVar, f.stack)))
  section(
    'Font sizes',
    fontSizes.length ? ['--text-*'] : [],
    fontSizes.flatMap((f) => [decl(f.cssVar, f.rem), ...(f.lineHeight ? [decl(f.lineHeight.cssVar, f.lineHeight.rem)] : [])]),
  )
  section('Font weights', fontWeights.length ? ['--font-weight-*'] : [], fontWeights.map((w) => decl(w.cssVar, String(w.value))))

  if (model.spacing.base) {
    const exceptions = model.spacing.scale.filter((s) => !s.conforms)
    section('Spacing', [], [
      decl('--spacing', model.spacing.base.rem),
      ...exceptions.map((s) => decl(`--spacing-${s.name}`, s.rem)),
    ])
  } else if (model.spacing.scale.length) {
    section('Spacing', [], model.spacing.scale.map((s) => decl(`--spacing-${s.name}`, s.rem)))
  }

  section('Radius', model.radius.length ? ['--radius-*'] : [], model.radius.map((r) => decl(r.cssVar, r.css)))
  if (model.shadows.length) resets.push('--shadow-*')
  section(
    'Shadows',
    [],
    model.shadows.filter((s) => !s.runtimeVar && s.light).map((s) => decl(s.cssVar, s.light.css)),
  )
  section('Breakpoints', model.breakpoints.length ? ['--breakpoint-*'] : [], model.breakpoints.map((b) => decl(b.cssVar, b.rem)))

  // Namespace resets must come before every other @theme block, otherwise they
  // would also clear the variables mapped in @theme inline.
  const themeIndex = lines.indexOf('@theme inline {')
  const resetBlock = ['@theme {', comment('Strict import: only imported tokens exist'), ...resets.map((r) => decl(r, 'initial')), '}', '']
  if (resets.length) {
    if (themeIndex === -1) lines.push(...resetBlock)
    else lines.splice(themeIndex, 0, ...resetBlock)
  }
  block('@theme', theme)

  return lines.join('\n').replace(/\n+$/, '\n')
}
