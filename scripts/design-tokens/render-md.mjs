/**
 * Render the merged DESIGN.md (DTCG tokens + Figma DESIGN.md + skill.md).
 *
 * Fixed section order, fixed table columns, no timestamps: the same model always
 * renders to the same bytes.
 */

const code = (s) => `\`${s}\``
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')

function table(headers, rows) {
  if (!rows.length) return ['_None._', '']
  return [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.map(esc).join(' | ')} |`),
    '',
  ]
}

const list = (items) => (items.length ? [...items.map((i) => `- ${i}`), ''] : ['_None._', ''])

const yamlString = (s) => (s === null || s === undefined ? 'null' : JSON.stringify(String(s)))

const colorCell = (v) => (v ? `${code(v.oklch)} ${v.hex}` : '—')

export function renderDesignMd(model) {
  const { meta, color, typography, spacing, sizing, radius, shadows, effects, breakpoints, opacity, layout, other, guidelines, report } = model
  const title = meta.title ?? 'Design System'
  const out = []
  const push = (...l) => out.push(...l)

  // --- Frontmatter ------------------------------------------------------------
  push(
    '---',
    `name: ${yamlString(meta.name)}`,
    `title: ${yamlString(title)}`,
    `description: ${yamlString(meta.description)}`,
    `schema: ${model.$schema}`,
    'source:',
    `  figma_file: ${yamlString(meta.source.figmaFile)}`,
    `  figma_page: ${yamlString(meta.source.figmaPage)}`,
    'generator:',
    `  name: ${meta.generator.name}`,
    `  version: ${meta.generator.version}`,
    `  style_dictionary: ${meta.generator.styleDictionary}`,
    'inputs:',
    ...meta.inputs.flatMap((i) => [`  - file: ${i.file}`, `    sha256: ${i.sha256}`]),
    '---',
    '',
    '<!-- GENERATED by `npm run tokens:build` from product/design-system/import/. Do not edit this file; edit the inputs and rebuild. -->',
    '',
    `# ${title} — Design System`,
    '',
    '> The single source of truth for product UI in this project. Token values come from',
    '> `import/tokens.json` (W3C DTCG) and are converted with Style Dictionary; colors are',
    '> OKLCH, dimensions rem. Guidance comes from the Figma `DESIGN.md` and `skill.md` exports.',
    '> Implementation: `tokens/tokens.css` (Tailwind CSS v4). Data: `tokens/tokens.json`.',
    '',
    '## Contents',
    '',
    '1. [Overview](#1-overview)',
    '2. [Rules](#2-rules)',
    '3. [Color](#3-color)',
    '4. [Typography](#4-typography)',
    '5. [Spacing and sizing](#5-spacing-and-sizing)',
    '6. [Radius](#6-radius)',
    '7. [Shadows and effects](#7-shadows-and-effects)',
    '8. [Breakpoints](#8-breakpoints)',
    '9. [Components](#9-components)',
    '10. [Accessibility](#10-accessibility)',
    '11. [Implementation (Tailwind CSS v4)](#11-implementation-tailwind-css-v4)',
    '12. [Provenance and import report](#12-provenance-and-import-report)',
    '',
  )

  // --- 1. Overview ---------------------------------------------------------------
  push('## 1. Overview', '')
  if (guidelines.mission) push(guidelines.mission, '')
  if (guidelines.brand.length) push('### Brand', '', ...list(guidelines.brand))
  if (guidelines.writingTone) push('### Writing tone', '', guidelines.writingTone, '')
  push(
    '### At a glance',
    '',
    ...table(
      ['Foundation', 'Count', 'Tailwind namespace'],
      [
        ['Semantic colors', String(color.semantic.length), code('--color-*') + ' via ' + code(':root') + ' / ' + code('.dark')],
        ['Palettes', `${color.palettes.length} (${color.palettes.reduce((s, p) => s + p.steps.length, 0)} steps)`, code('--color-*')],
        ['Alpha colors', String(color.alpha.reduce((s, g) => s + g.steps.length, 0)), code('--color-*-alpha-*')],
        ['Font families', String(typography.fontFamilies.length), code('--font-*')],
        ['Font sizes', String(typography.fontSizes.length), code('--text-*')],
        ['Font weights', String(typography.fontWeights.length), code('--font-weight-*')],
        ['Spacing steps', String(spacing.scale.length), code('--spacing')],
        ['Radius', String(radius.length), code('--radius-*')],
        ['Shadows', String(shadows.length), code('--shadow-*')],
        ['Breakpoints', String(breakpoints.length), code('--breakpoint-*')],
      ],
    ),
  )

  // --- 2. Rules ------------------------------------------------------------------
  push('## 2. Rules', '')
  push(
    '### Token usage (always)',
    '',
    '- Product UI **must** use the tokens in this file through their Tailwind utilities (for example `bg-primary`, `text-muted-foreground`, `rounded-md`, `shadow-sm`).',
    '- Semantic colors **must** be preferred over palette steps; palette steps are for data visualization and exceptions.',
    '- Raw hex, rgb or arbitrary values (`bg-[#…]`, `p-[13px]`) **must not** be used when a token exists.',
    '- Every color utility **must** work in light and dark mode; semantic colors switch automatically via `.dark`.',
    '',
  )
  if (guidelines.rulesDo.length) push('### Do', '', ...list(guidelines.rulesDo))
  if (guidelines.rulesDont.length) push("### Don't", '', ...list(guidelines.rulesDont))
  if (guidelines.componentRules.length) push('### Component rules', '', ...list(guidelines.componentRules))
  if (guidelines.qualityGates.length) push('### Quality gates', '', ...list(guidelines.qualityGates))

  // --- 3. Color --------------------------------------------------------------------
  push('## 3. Color', '')
  push(
    '### 3.1 Semantic colors (light / dark)',
    '',
    'Defined as runtime variables in `:root` and `.dark`, mapped to Tailwind with `@theme inline`.',
    '',
    ...table(
      ['Token', 'Utility', 'Light', 'Dark'],
      color.semantic.map((c) => [code(c.name), code(c.utility), colorCell(c.light), colorCell(c.dark)]),
    ),
  )
  if (color.custom.length) {
    push(
      '### 3.2 Custom colors',
      '',
      ...table(
        ['Token', 'Variable', 'Light', 'Dark'],
        color.custom.map((c) => [code(c.name), code(c.cssVar), colorCell(c.light), colorCell(c.dark)]),
      ),
    )
  }
  if (color.alpha.length) {
    push('### 3.3 Alpha colors', '', 'Transparent tints for surfaces, hovers and focus halos.', '')
    const steps = [...new Set(color.alpha.flatMap((g) => g.steps.map((s) => s.step)))]
    push(
      ...table(
        ['Role', ...steps.map((s) => `${s}`)],
        color.alpha.map((g) => [code(g.name), ...steps.map((st) => {
          const s = g.steps.find((x) => x.step === st)
          return s ? code(s.value.oklch) : '—'
        })]),
      ),
      `Utility: ${code('bg-{role}-alpha-{step}')}, for example ${code('bg-primary-alpha-10')}.`,
      '',
    )
  }
  push('### 3.4 Palettes', '')
  for (const p of color.palettes) {
    push(
      `#### ${p.name}`,
      '',
      ...table(['Step', 'Variable', 'OKLCH', 'Hex'], p.steps.map((s) => [s.step, code(s.cssVar), code(s.value.oklch), s.value.hex])),
    )
  }
  if (color.gradients.length) {
    push(
      '### 3.5 Gradients (Figma styles)',
      '',
      'Gradients are Figma paint styles, not DTCG tokens; they are not part of `tokens.css`. Direction is not exported — choose it per use.',
      '',
      ...table(
        ['Style', 'Stops', 'CSS'],
        color.gradients.map((g) => [
          g.label,
          g.stops.map((s) => `${s.hex} ${s.position}`).join(' → ') + (g.complete ? '' : ' (truncated in export)'),
          g.css ? code(g.css) : '—',
        ]),
      ),
    )
  }

  // --- 4. Typography --------------------------------------------------------------------
  push('## 4. Typography', '')
  push(
    '### 4.1 Font families',
    '',
    ...table(['Token', 'Family', 'Utility', 'Stack'], typography.fontFamilies.map((f) => [code(f.name), f.family, code(`font-${f.name}`), code(f.stack)])),
    '### 4.2 Type scale',
    '',
    ...table(
      ['Token', 'Utility', 'Size', 'Line height'],
      typography.fontSizes.map((f) => [
        code(f.name),
        code(`text-${f.name}`),
        `${f.rem} (${f.px}px)`,
        f.lineHeight ? `${f.lineHeight.rem} (${f.lineHeight.px}px)` : '— (not set)',
      ]),
    ),
    '### 4.3 Font weights',
    '',
    ...table(['Token', 'Utility', 'Weight'], typography.fontWeights.map((w) => [code(w.name), code(`font-${w.name}`), String(w.value)])),
  )
  if (typography.textStyles.length) {
    push(
      '### 4.4 Text styles (Figma)',
      '',
      ...table(
        ['Style', 'Family', 'Weight', 'Size / line height', 'Utilities'],
        typography.textStyles.map((t) => [t.label, t.family, `${t.weight}${t.weightValue ? ` (${t.weightValue})` : ''}`, `${t.sizePx}px / ${t.lineHeightPx}px`, t.utilities ? code(t.utilities) : '—']),
      ),
    )
  }

  // --- 5. Spacing ------------------------------------------------------------------------
  push('## 5. Spacing and sizing', '')
  if (spacing.base) {
    push(
      `Base unit: ${code(`--spacing: ${spacing.base.rem}`)} (${spacing.base.px}px). Tailwind v4 derives \`p-*\`, \`m-*\`, \`gap-*\`, \`w-*\`, \`h-*\` from it: \`p-4\` = 4 × ${spacing.base.px}px.`,
      '',
    )
  }
  push(
    ...table(
      ['Step', 'Size', 'Conforms to base'],
      spacing.scale.map((s) => [code(s.name), `${s.rem} (${s.px}px)`, s.conforms ? 'yes' : `no — emitted as ${code(`--spacing-${s.name}`)}`]),
    ),
  )
  if (sizing.length) {
    push(
      '### Sizing scales',
      '',
      ...table(
        ['Scale', 'Steps', 'Matches spacing'],
        sizing.map((g) => [g.group, String(g.items.length), g.items.every((i) => i.matchesSpacing) ? 'all steps' : `${g.items.filter((i) => i.matchesSpacing).length} of ${g.items.length}`]),
      ),
    )
  }
  if (layout.length) push('### Layout', '', ...table(['Token', 'Size'], layout.map((l) => [code(l.name), `${l.rem} (${l.px}px)`])))

  // --- 6. Radius -------------------------------------------------------------------------
  push('## 6. Radius', '', ...table(['Token', 'Utility', 'Value'], radius.map((r) => [code(r.name), code(`rounded-${r.name}`), `${r.css}${r.px >= 9999 ? ' (pill)' : ` (${r.px}px)`}`])))

  // --- 7. Shadows ------------------------------------------------------------------------
  push(
    '## 7. Shadows and effects',
    '',
    ...table(
      ['Token', 'Utility', 'Light', 'Dark'],
      shadows.map((s) => [code(s.name), code(`shadow-${s.name}`), s.light ? code(s.light.css) : '—', s.dark ? code(s.dark.css) : '— (light value)']),
    ),
  )
  if (effects.length) {
    push('### Blur effects (Figma)', '', ...table(['Style', 'Kind', 'Radius'], effects.map((e) => [e.label, code(e.kind), `${e.px}px`])))
  }
  if (opacity.length) push('### Opacity scale', '', `Values: ${opacity.map((o) => o.name).join(', ')} — use Tailwind ${code('opacity-*')} directly.`, '')

  // --- 8. Breakpoints --------------------------------------------------------------------
  push('## 8. Breakpoints', '', ...table(['Token', 'Prefix', 'Min width'], breakpoints.map((b) => [code(b.name), code(`${b.name}:`), `${b.rem} (${b.px}px)`])))

  // --- 9. Components ---------------------------------------------------------------------
  push('## 9. Components', '')
  const { families, variantAxes } = guidelines.components
  if (families.length) push('### Families', '', ...list(families))
  if (variantAxes.length) push('### Variant axes', '', ...table(['Axis', 'Values'], variantAxes.map((a) => [a.axis, a.values.join(', ')])))
  if (!families.length && !variantAxes.length) push('_No component families imported._', '')
  if (guidelines.gridStyles.length) push('### Grid styles', '', ...list(guidelines.gridStyles))
  if (other.length) {
    push('### Component configuration values', '', ...table(['Path', 'Value'], other.filter((o) => o.category === 'component-config').map((o) => [code(o.path), code(JSON.stringify(o.value))])))
  }

  // --- 10. Accessibility -----------------------------------------------------------------
  push('## 10. Accessibility', '', ...list(guidelines.accessibility.length ? guidelines.accessibility : ['Target: WCAG 2.2 AA']))
  for (const a of guidelines.additional) push(`### ${a.heading} (${a.file})`, '', a.markdown, '')

  // --- 11. Implementation ----------------------------------------------------------------
  push(
    '## 11. Implementation (Tailwind CSS v4)',
    '',
    '```css',
    '/* app.css */',
    '@import "tailwindcss";',
    '@import "./tokens.css"; /* product/design-system/tokens/tokens.css */',
    '```',
    '',
    '```tsx',
    '<button className="bg-primary text-primary-foreground rounded-md px-4 py-2 shadow-sm',
    '                   hover:bg-primary/90 focus-visible:ring-2 focus-visible:ring-ring">',
    '  Save',
    '</button>',
    '```',
    '',
    '- Dark mode is class-based: add `dark` to `<html>`; `.dark` swaps every semantic color and shadow.',
    '- Default Tailwind namespaces that the import provides are reset (`--color-*: initial`), so only imported tokens are available.',
    '- No `tailwind.config.js` — Tailwind CSS v4 reads the theme from CSS.',
    '',
  )

  // --- 12. Provenance --------------------------------------------------------------------
  push(
    '## 12. Provenance and import report',
    '',
    '### Inputs',
    '',
    ...table(['File', 'SHA-256', 'Bytes'], meta.inputs.map((i) => [code(i.file), code(i.sha256), String(i.bytes)])),
  )
  if (meta.variableCollections.length) push('### Figma variable collections', '', ...list(meta.variableCollections))
  push(
    '### Counts',
    '',
    ...table(
      ['Tokens in tokens.json', 'CSS variables', 'Documented only', 'Warnings'],
      [[String(meta.counts.tokens), String(meta.counts.cssVariables), String(meta.counts.documentedOnly), String(meta.counts.warnings)]],
    ),
    '### Source sections',
    '',
    ...table(['File', 'Section', 'Status', 'Note'], report.sources.map((s) => [s.file, s.heading, s.status, s.reason])),
    '### Not emitted to tokens.css',
    '',
    ...table(['Category', 'Tokens', 'Reason'], report.notEmitted.map((n) => [code(n.category), String(n.count), n.reason])),
    '### Normalizations and warnings',
    '',
    ...table(
      ['Severity', 'Code', 'Count', 'Summary', 'Examples'],
      report.issues.map((i) => [i.severity, code(i.code), String(i.count), i.summary, i.items.slice(0, 3).map((x) => `${code(x.path)}: ${x.detail}`).join('; ') + (i.items.length > 3 ? '; …' : '')]),
    ),
    'Full details: `tokens/tokens.json` → `report`.',
    '',
  )

  return out.join('\n').replace(/\n+$/, '\n')
}
